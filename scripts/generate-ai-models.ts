/**
 * Writes the catalog of `@tanstack/ai-models`:
 * - `src/providers/<id>.ts`: one file per provider (a subpath export each)
 * - `src/catalog.ts`: every provider, and the `generatedAt` date
 * - the `exports` of `package.json`
 *
 * Input: `scripts/models-dev.models.json` (from `scripts/fetch-models-dev.ts`)
 * and the OpenRouter and Vercel lists of the existing fetchers.
 *
 * Usage:
 *   pnpm tsx scripts/generate-ai-models.ts
 */

import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { models as openrouterModels } from './openrouter.models'
import { models as vercelModels } from './vercel-gateway.models'
import {
  buildModels,
  buildProvider,
} from '../packages/ai-models/scripts/catalog'
import { PROVIDERS } from '../packages/ai-models/scripts/providers'
import { fromOpenRouter, fromVercel } from './model-sync/gateway-models'
import type { DevCatalog } from '../packages/ai-models/scripts/catalog'

const here = dirname(fileURLToPath(import.meta.url))
const packageDir = resolve(here, '../packages/ai-models')
const providersDir = resolve(packageDir, 'src/providers')

/** `qwen-token-plan-cn` as `qwenTokenPlanCn`. */
const identifier = (id: string) =>
  id.replace(/-([a-z0-9])/g, (_match, char: string) => char.toUpperCase())

const HEADER =
  '// Generated by scripts/generate-ai-models.ts from models.dev. Do not edit.\n'

async function main() {
  const dev: DevCatalog = JSON.parse(
    await readFile(resolve(here, 'models-dev.models.json'), 'utf8'),
  )
  const gateways = {
    openrouter: openrouterModels.map(fromOpenRouter),
    'vercel-ai-gateway': vercelModels.map(fromVercel),
  }

  await rm(providersDir, { recursive: true, force: true })
  await mkdir(providersDir, { recursive: true })
  let total = 0
  for (const row of PROVIDERS) {
    const models = buildModels(row, { dev, gateways })
    const provider = buildProvider(row, models)
    total += models.length
    await writeFile(
      resolve(providersDir, `${row.id}.ts`),
      `${HEADER}import type { ModelRecord, ProviderRecord } from '../types'

/** ${row.name}. */
export const provider: ProviderRecord = ${JSON.stringify(provider)}

/** Every ${row.name} model, sorted by id. */
export const models: ReadonlyArray<ModelRecord> = ${JSON.stringify(models)}
`,
    )
  }

  const ids = PROVIDERS.map((row) => row.id)
  const generatedAt = new Date().toISOString().slice(0, 10)
  await writeFile(
    resolve(packageDir, 'src/catalog.ts'),
    `${HEADER}${ids
      .map((id) => `import * as ${identifier(id)} from './providers/${id}'`)
      .join('\n')}

/** The day the catalog was generated, as \`YYYY-MM-DD\`. */
export const generatedAt = '${generatedAt}'

/** Every provider module, in id order. */
export const providerModules = [${ids.map(identifier).join(', ')}]
`,
  )

  // One subpath per provider, so a build ships only the providers it uses.
  const packageJsonPath = resolve(packageDir, 'package.json')
  const packageJson = JSON.parse(await readFile(packageJsonPath, 'utf8'))
  packageJson.exports = {
    '.': {
      types: './dist/esm/index.d.ts',
      import: './dist/esm/index.js',
    },
    ...Object.fromEntries(
      ids.map((id) => [
        `./${id}`,
        {
          types: `./dist/esm/providers/${id}.d.ts`,
          import: `./dist/esm/providers/${id}.js`,
        },
      ]),
    ),
  }
  await writeFile(packageJsonPath, `${JSON.stringify(packageJson, null, 2)}\n`)
  console.log(`Wrote ${ids.length} providers and ${total} models.`)
}

await main()
