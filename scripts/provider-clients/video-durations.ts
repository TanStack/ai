/**
 * Video duration tables, from the `duration` (or `seconds`) input of the
 * modelschemas video activity documents. The adapters pass them to
 * `snapToDurationOption`.
 */
import type { ActivityDoc, Schema } from './fal.ts'

export type Duration =
  | { kind: 'discrete'; values: Array<string | number> }
  | { kind: 'range'; min: number; max: number; step?: number }

/**
 * Providers whose video models share one create operation. The model ids
 * come from the `model` enum of that operation's request body.
 */
export const VIDEO_DURATIONS = [
  {
    id: 'openai',
    path: '/videos',
    outDir: 'packages/ai-openai/src/video/generated',
  },
  {
    id: 'grok',
    path: '/v1/videos/generations',
    outDir: 'packages/ai-grok/src/video/generated',
  },
]

function deref(schema: Schema | undefined, schemas: Record<string, Schema>) {
  return schema?.$ref ? schemas[schema.$ref.split('/').pop() ?? ''] : schema
}

/** A video input's `duration` schema as `DurationOptions`, if it has one. */
export function durationOf(
  schema: Schema | undefined,
  schemas: Record<string, Schema>,
): Duration | undefined {
  if (!schema) return undefined
  if (schema.$ref) return durationOf(deref(schema, schemas), schemas)
  if (Array.isArray(schema.enum)) {
    const values = schema.enum.filter(
      (value): value is string | number =>
        typeof value === 'string' || typeof value === 'number',
    )
    return { kind: 'discrete', values }
  }
  const { minimum, maximum, multipleOf } = schema
  if (typeof minimum === 'number' && typeof maximum === 'number') {
    return {
      kind: 'range',
      min: minimum,
      max: maximum,
      ...(typeof multipleOf === 'number' && { step: multipleOf }),
    }
  }
  for (const part of schema.anyOf ?? schema.oneOf ?? []) {
    const found = durationOf(part, schemas)
    if (found) return found
  }
  return undefined
}

/** Every string `enum` value in a schema and its `anyOf` / `oneOf` parts. */
function enumOf(
  schema: Schema | undefined,
  schemas: Record<string, Schema>,
): Array<string> {
  const resolved = deref(schema, schemas)
  if (!resolved) return []
  const own = Array.isArray(resolved.enum)
    ? resolved.enum.filter((v): v is string => typeof v === 'string')
    : []
  const parts = [...(resolved.anyOf ?? []), ...(resolved.oneOf ?? [])]
  return [...own, ...parts.flatMap((part) => enumOf(part, schemas))]
}

/**
 * Per model, the duration options of one create operation. Throws when the
 * operation, its model enum or its duration input is gone, so a changed
 * document fails the generator instead of emptying the table.
 */
export function operationVideoDurations(doc: ActivityDoc, path: string) {
  const schemas = doc.components?.schemas ?? {}
  const content = doc.paths?.[path]?.post?.requestBody?.content ?? {}
  const body = deref(Object.values(content)[0]?.schema, schemas)
  const props = body?.properties ?? {}
  const duration = durationOf(props.duration ?? props.seconds, schemas)
  const models = enumOf(props.model, schemas)
  if (!duration || models.length === 0) {
    throw new Error(`No model enum and duration on POST ${path}`)
  }
  return new Map(models.map((model) => [model, duration]))
}

/** The `video-durations.ts` module text. */
export function renderVideoDurations(
  provider: string,
  durations: Map<string, Duration>,
) {
  const entries = [...durations.keys()]
    .sort()
    .map((id) => {
      const d = durations.get(id)
      const body =
        d?.kind === 'discrete'
          ? `kind: 'discrete', values: ${JSON.stringify(d.values)}`
          : `kind: 'range', min: ${d?.min}, max: ${d?.max},${d?.step ? ` step: ${d.step},` : ''} unit: 'seconds'`
      return `  '${id}': { ${body} },`
    })
    .join('\n')
  const name = `${provider.toUpperCase().replaceAll('-', '_')}_VIDEO_DURATIONS`
  return `// Generated by scripts/provider-clients/generate.ts from the modelschemas
// ${provider} video activity document. Do not edit. Run \`pnpm generate:provider-clients\`.
//
// The \`duration\` options of each ${provider} video endpoint that takes one. An
// endpoint that is not listed takes no duration.

export const ${name} = {
${entries}
} as const
`
}
