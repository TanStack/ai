/**
 * Converts LLM Gateway catalog rows into packages/ai-llmgateway/src/model-meta.ts.
 *
 * Usage:
 *   node scripts/convert-llmgateway-models.ts
 */

import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { catalogRowToMeta } from './model-sync/llmgateway.ts'
import {
  reasoningShapeName,
  reasoningShapeTable,
} from './model-sync/reasoning-shapes.ts'
import { models } from './llmgateway.models.ts'
import type { LlmGatewayModelMeta } from './model-sync/llmgateway'
import type { ReasoningShape } from './model-sync/reasoning-shapes'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUTPUT_PATH = resolve(
  __dirname,
  '../packages/ai-llmgateway/src/model-meta.ts',
)

function formatStringArray(ids: Array<string>): string {
  return `[\n${ids.map((id) => `  ${JSON.stringify(id)},`).join('\n')}\n] as const`
}

function formatModalitiesType(input: LlmGatewayModelMeta['input']): string {
  return `readonly [${input.map((modality) => `'${modality}'`).join(', ')}]`
}

function formatModalitiesValue(input: LlmGatewayModelMeta['input']): string {
  return `[${input.map((modality) => `'${modality}'`).join(', ')}] as const`
}

function convertModels(rows: Array<LlmGatewayModelMeta>): string {
  const modalityEntries = rows
    .map(
      (row) =>
        `  ${JSON.stringify(row.id)}: ${formatModalitiesType(row.input)}`,
    )
    .join('\n')

  const shapes: Array<ReasoningShape> = []
  const reasoningEntries: Array<string> = []
  for (const row of rows) {
    if (!row.reasoning) continue
    shapes.push(row.reasoning)
    reasoningEntries.push(
      `  ${JSON.stringify(row.id)}: ${reasoningShapeName(row.reasoning)},`,
    )
  }
  const reasoningBlock =
    reasoningEntries.length === 0
      ? ''
      : `
${reasoningShapeTable(shapes).code}

const LLMGATEWAY_REASONING = {
${reasoningEntries.join('\n')}
} satisfies Partial<Record<LLMGatewayChatModels, ModelReasoning>>

/**
 * Each chat model's reasoning levels for \`chat({ reasoning })\`.
 * A model that is not here does not reason. No model takes a token budget.
 */
export type LLMGatewayModelReasoningByName = {
  [K in keyof typeof LLMGATEWAY_REASONING]: ModelReasoningCapability<
    (typeof LLMGATEWAY_REASONING)[K]
  >
}

/**
 * Runtime map from chat model name to its reasoning data.
 * An unknown name gives \`undefined\`: the adapter sends no reasoning field.
 */
export const LLMGATEWAY_MODEL_REASONING: Readonly<
  Record<string, ModelReasoning>
> = LLMGATEWAY_REASONING
`

  return `/**
 * This file is generated by scripts/convert-llmgateway-models.ts. Do not edit by hand.
 *
 * Source: https://api.llmgateway.io/v1/models (modelschemas has no llmgateway provider).
 * Unprefixed ids only. A \`provider/\` prefix still works at runtime.
 */

import type { Modality, ModelReasoning } from '@tanstack/ai'
import type { ModelReasoningCapability } from '@tanstack/ai/adapter-internals'
import type { LLMGatewayTextProviderOptions } from './text/text-provider-options'

export const LLMGATEWAY_CHAT_MODELS = ${formatStringArray(rows.map((row) => row.id))}

export type LLMGatewayChatModels = (typeof LLMGATEWAY_CHAT_MODELS)[number]

/**
 * A catalog model name, or any other id. A \`provider/\` prefix pins routing.
 * An id outside the catalog gets text-only input and the generic options.
 */
export type LLMGatewayModelId = LLMGatewayChatModels | (string & {})

export type LLMGatewayModelInputModalitiesByName = {
${modalityEntries}
}

export const LLMGATEWAY_MODEL_INPUT_MODALITIES: Readonly<
  Record<string, ReadonlyArray<Modality>>
> = {
${rows
  .map(
    (row) =>
      `  ${JSON.stringify(row.id)}: ${formatModalitiesValue(row.input)},`,
  )
  .join('\n')}
} satisfies LLMGatewayModelInputModalitiesByName

export type LLMGatewayChatModelProviderOptionsByName = {
  [K in LLMGatewayChatModels]: LLMGatewayTextProviderOptions
}

/** LLM Gateway exposes no provider-specific tool factories. */
export type LLMGatewayChatModelToolCapabilitiesByName = {
  [K in LLMGatewayChatModels]: readonly []
}

export type ResolveProviderOptions<TModel extends string> =
  TModel extends keyof LLMGatewayChatModelProviderOptionsByName
    ? LLMGatewayChatModelProviderOptionsByName[TModel]
    : LLMGatewayTextProviderOptions

export type ResolveInputModalities<TModel extends string> =
  TModel extends keyof LLMGatewayModelInputModalitiesByName
    ? LLMGatewayModelInputModalitiesByName[TModel]
    : readonly ['text']
${reasoningBlock}`
}

async function main() {
  const rows = models
    .map((model) => catalogRowToMeta(model))
    .filter((model): model is LlmGatewayModelMeta => model !== null)
    .sort((a, b) => a.id.localeCompare(b.id))
  if (rows.length === 0) {
    throw new Error(
      'LLM Gateway catalog produced no chat models. Refusing to overwrite model-meta.ts.',
    )
  }
  console.log(`Writing ${rows.length} LLM Gateway chat models`)
  await writeFile(OUTPUT_PATH, convertModels(rows), 'utf-8')
  console.log(`Model meta file written to ${OUTPUT_PATH}`)
}

main().catch((error: unknown) => {
  console.error(error)
  process.exit(1)
})
