/**
 * Writes each provider package's model catalog (its `./models` subpath) from
 * modelschemas, and a patch changeset for each package whose models changed.
 * One call: modelschemas allows 60 anonymous calls an hour.
 *
 * Usage:
 *   node scripts/sync-model-catalogs.ts
 */

import { existsSync } from 'node:fs'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { writeSyncChangeset } from './model-sync/changeset.ts'
import {
  CATALOGS,
  buildRecords,
  isChatModel,
} from './model-sync/model-catalog.ts'
import type { SchemaModel } from './model-sync/model-catalog'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const API_URL = 'https://modelschemas.com/v1/models?pricing=1'

const response = await fetch(API_URL)
if (!response.ok)
  throw new Error(`modelschemas answered ${response.status} for ${API_URL}`)
const body = (await response.json()) as {
  count: number
  models: Array<SchemaModel>
}
if (body.models.length !== body.count)
  throw new Error(
    `modelschemas sent ${body.models.length} of ${body.count} models`,
  )

const changed = new Set<string>()
for (const catalog of CATALOGS) {
  const rows = body.models.filter(
    (model) => model.provider === catalog.source && isChatModel(model),
  )
  if (rows.length === 0)
    throw new Error(`modelschemas has no chat models for '${catalog.source}'`)
  const records = buildRecords(rows)
  const file = resolve(ROOT, catalog.file)
  const before: unknown = existsSync(file)
    ? (await import(pathToFileURL(file).href)).models
    : undefined
  if (JSON.stringify(before) === JSON.stringify(records)) continue
  await writeFile(
    file,
    `// Generated by scripts/sync-model-catalogs.ts from modelschemas. Do not edit.
import type { ModelRecord } from '@tanstack/ai'

/** Every ${catalog.name} chat model on modelschemas.com, sorted by id. */
export const models: ReadonlyArray<ModelRecord> = ${JSON.stringify(records)}
`,
  )
  const packageJson = resolve(dirname(file), '..', 'package.json')
  changed.add(JSON.parse(await readFile(packageJson, 'utf8')).name)
  console.log(`${catalog.file}: ${records.length} models`)
}

if (changed.size > 0) await writeSyncChangeset(ROOT, changed)
